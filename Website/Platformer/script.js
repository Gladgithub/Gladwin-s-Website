function syncPlayer(){
    if(!socketReady){
        return;
    }

    var now = Date.now();
    if(now - lastSocketUpdate < 33){
        return;
    }

    lastSocketUpdate = now;
    socket.emit("playerState", getLocalPlayerState());
}

